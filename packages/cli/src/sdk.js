// Generate a standalone, typed ES module SDK from a server's real RTC catalog.
import { mkdir, mkdtemp, writeFile, rename, rm, lstat } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { byName, requirePass } from './dispatch.js';
import { toolPages } from './pages.js';
import { ToolError } from './http.js';

const safe = /^[a-z][a-z0-9_]*$/;
export function typeFromSchema(schema, depth = 0) {
  if (depth > 8 || !schema || typeof schema !== 'object') return 'unknown';
  if (Array.isArray(schema.enum) && schema.enum.length) {
    if (!schema.enum.every((x) => ['string', 'number', 'boolean'].includes(typeof x))) return 'unknown';
    return schema.enum.map((x) => JSON.stringify(x)).join(' | ');
  }
  const union = schema.oneOf || schema.anyOf;
  if (Array.isArray(union)) return union.map((x) => typeFromSchema(x, depth + 1)).join(' | ');
  if (schema.type === 'string') return 'string';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'null') return 'null';
  if (schema.type === 'array') return 'Array<' + typeFromSchema(schema.items, depth + 1) + '>';
  if (schema.type === 'object') {
    const properties = Object.entries(schema.properties || {});
    const required = new Set(schema.required || []);
    const fields = properties.map(([key, v]) => JSON.stringify(key) +
      (required.has(key) ? ': ' : '?: ') + typeFromSchema(v, depth + 1));
    if (schema.additionalProperties) return 'Record<string, unknown>' +
      (fields.length ? ' & { ' + fields.join('; ') + ' }' : '');
    return fields.length ? '{ ' + fields.join('; ') + ' }' : 'Record<string, unknown>';
  }
  return 'unknown';
}
function render(tools) {
  const js = ["import { call } from './_client.js';"];
  const types = ["import type { RtoolResult } from './_client.js';"];
  for (const tool of tools) {
    if (!safe.test(tool.name)) throw new ToolError('Unsafe tool name in catalog');
    js.push('export async function ' + tool.name + '(args = {}) {',
      '  return call(' + JSON.stringify(tool.name) + ', args);', '}');
    types.push('export declare function ' + tool.name + '(args?: ' +
      typeFromSchema(tool.inputSchema) + '): Promise<RtoolResult>;');
  }
  return { js: js.join('\n') + '\n', types: types.join('\n') + '\n' };
}
function runtime(url, name) {
  const passVar = 'RTOOL_PASS_' + name.toUpperCase().replaceAll('-', '_');
  return [
    '// Generated by rtool. No secret is stored in this SDK.',
    'const base = ' + JSON.stringify(url) + ';',
    'const passKey = ' + JSON.stringify(passVar) + ';',
    'export async function call(name, args = {}) {',
    '  const pass = process.env[passKey];',
    "  if (!pass) throw new Error('No pass is available for this service');",
    "  const url = new URL('/api/tools/' + encodeURIComponent(name), base);",
    '  const r = await fetch(url, {',
    "    method: 'POST', headers: { authorization: 'Bearer ' + pass, 'content-type': 'application/json' },",
    '    body: JSON.stringify(args), signal: AbortSignal.timeout(12000)',
    '  });',
    '  let data;',
    "  try { data = await r.json(); } catch { throw new Error('Service did not return JSON'); }",
    '  if (!r.ok || data.ok === false) {',
    "    const code = String(data?.error?.code || 'service_error');",
    "    const e = new Error('RTC call failed: ' + code);",
    '    e.code = code; throw e;',
    '  }',
    '  return data;',
    '}',
    ''
  ].join('\n');
}
export async function generateSdk({ servers, env = process.env, name, dest }) {
  const server = byName(servers, env, name);
  requirePass(server);
  const areas = new Map();
  const seen = new Set();
  for await (const page of toolPages(server, '/api/tools?listing=catalog&limit=100')) {
    for (const tool of page) {
      if (!safe.test(tool.name || '') || !safe.test(tool.area || '') || seen.has(tool.name))
        throw new ToolError('Duplicate or unsafe SDK tool metadata');
      seen.add(tool.name);
      if (seen.size > 5000) throw new ToolError('Catalog exceeds SDK safety limit');
      if (!areas.has(tool.area)) areas.set(tool.area, []);
      areas.get(tool.area).push(tool);
    }
  }
  if (!seen.size) throw new ToolError('No RTC tools available to export');
  const target = resolve(dest || join(process.cwd(), 'rtool-sdk', name));
  const parent = dirname(target);
  await mkdir(parent, { recursive: true, mode: 0o700 });
  try { await lstat(target); throw new ToolError('SDK output already exists; refusing overwrite'); }
  catch (e) { if (e.code !== 'ENOENT') throw e; }
  const staged = await mkdtemp(join(parent, '.rtool-sdk-stage-'));
  try {
    await writeFile(join(staged, 'package.json'), '{"private":true,"type":"module"}\n',
      { flag: 'wx' });
    await writeFile(join(staged, '_client.js'), runtime(server.url, name), { flag: 'wx' });
    await writeFile(join(staged, '_client.d.ts'),
      'export interface RtoolResult { ok: boolean; result?: unknown; handle?: string }\n' +
      'export declare function call(name: string, args?: Record<string, unknown>): Promise<RtoolResult>;\n',
      { flag: 'wx' });
    for (const [area, entries] of areas) {
      const rendered = render(entries);
      await writeFile(join(staged, area + '.js'), rendered.js, { flag: 'wx' });
      await writeFile(join(staged, area + '.d.ts'), rendered.types, { flag: 'wx' });
    }
    await rename(staged, target);
  } catch (e) {
    await rm(staged, { recursive: true, force: true });
    throw e;
  }
  return { output: target, count: seen.size, areas: [...areas.keys()] };
}
